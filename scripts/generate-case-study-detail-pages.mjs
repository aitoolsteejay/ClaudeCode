// Builds the detailed case study pages that use components/case-studies/CaseStudyLayout from
// content/case-study-pages/*.json (the files the Keystatic admin edits):
//   - app/case-studies/<slug>/page.tsx          thin page with literal metadata and <CaseStudyLayout />
//   - lib/case-study-detail-cards.generated.json the cards the /case-studies listing reads
//   - the entries in app/sitemap.ts              between two marker comments
// (The 50 library case studies are built by generate-case-study-pages.mjs from lib/case-study-library.json;
// twelve long-form case studies are still hand-built pages.)
//
//   node scripts/generate-case-study-detail-pages.mjs           write everything
//   node scripts/generate-case-study-detail-pages.mjs --check   exit 1 if anything is out of date
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const CHECK = process.argv.includes("--check");
const dir = path.join(root, "content/case-study-pages");
const j = (v) => JSON.stringify(v);
const list = (items) => `[\n${items.map((x) => `        ${j(x)},`).join("\n")}\n      ]`;
const objs = (items) => `[\n${items.map((o) => `        ${j(o)},`).join("\n")}\n      ]`;

const REQUIRED = ["metaTitle", "metaDescription", "ogTitle", "ogDescription", "schemaHeadline", "schemaDescription", "datePublished", "dateModified", "tag", "accent", "title", "intro", "challengeTitle", "approachTitle", "outcomeTitle", "outcomeBody", "roleBody", "industry", "indexTitle", "excerpt"];

const page = (d) => `// Generated by scripts/generate-case-study-detail-pages.mjs from content/case-study-pages/${d.slug}.json. Edit the data, not this file.
import type { Metadata } from "next";
import CaseStudyLayout from "@/components/case-studies/CaseStudyLayout";
import { buildArticleSchema } from "@/lib/schema";

const URL = "https://www.myntmore.com/case-studies/${d.slug}";

export const metadata: Metadata = {
  title: ${j(d.metaTitle)},
  description: ${j(d.metaDescription)},
  keywords: [
${d.keywords.map((k) => `    ${j(k)},`).join("\n")}
  ],
  alternates: { canonical: URL },
  openGraph: {
    title: ${j(d.ogTitle)},
    description: ${j(d.ogDescription)},
    url: URL,
    images: [{ url: "/og-image.png", width: 1200, height: 630, alt: "Myntmore" }],
  },
};

const ARTICLE_SCHEMA = buildArticleSchema({
  headline: ${j(d.schemaHeadline)},
  description: ${j(d.schemaDescription)},
  url: URL,
  datePublished: ${j(d.datePublished)},
  dateModified: ${j(d.dateModified)},
});

export default function CaseStudyPage() {
  return (
    <CaseStudyLayout
      slug={${j(d.slug)}}
      tag={${j(d.tag)}}
      accent={${j(d.accent)}}
      title={${j(d.title)}}
      intro={${j(d.intro)}}
      heroStats={${objs(d.heroStats)}}
      challengeTitle={${j(d.challengeTitle)}}
      challengeBody={${list(d.challengeBody)}}
      approachTitle={${j(d.approachTitle)}}
      approachBody={${list(d.approachBody)}}
      metrics={${objs(d.metrics)}}
      outcomeTitle={${j(d.outcomeTitle)}}
      outcomeBody={${j(d.outcomeBody)}}
      roleBody={${j(d.roleBody)}}
      services={${objs(d.services)}}
      articleSchema={ARTICLE_SCHEMA}
    />
  );
}
`;

const problems = [];
const cases = [];
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort()) {
  const slug = f.replace(/\.json$/, "");
  const d = { ...JSON.parse(fs.readFileSync(path.join(dir, f), "utf8")), slug };
  for (const k of REQUIRED) if (!d[k]) problems.push(`${f}: "${k}" is empty`);
  for (const [k, n] of [["heroStats", 3]]) if (!Array.isArray(d[k]) || d[k].length !== n) problems.push(`${f}: "${k}" must have exactly ${n} items`);
  for (const k of ["challengeBody", "approachBody", "metrics", "services", "indexStats"]) if (!Array.isArray(d[k]) || !d[k].length) problems.push(`${f}: "${k}" is empty`);
  d.keywords ??= [];
  d.indexServices ??= [];
  if (d.metaTitle && d.metaTitle.length + " | Myntmore".length > 60) problems.push(`${f}: search title is ${d.metaTitle.length + 11} characters with the site suffix, over 60`);
  cases.push(d);
}
if (problems.length) { console.error(problems.join("\n")); process.exit(1); }

let stale = 0, wrote = 0;
const writeIf = (file, next) => {
  const prev = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  if (prev === next) return;
  stale++;
  if (!CHECK) { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, next); wrote++; }
  else console.error(`${path.relative(root, file)} is out of date`);
};

for (const d of cases) writeIf(path.join(root, "app/case-studies", d.slug, "page.tsx"), page(d));

const cards = cases.map((d) => ({
  slug: d.slug, tag: d.tag, industry: d.industry, accent: d.accent, title: d.indexTitle,
  stats: d.indexStats, excerpt: d.excerpt, services: d.indexServices,
  ...(Number.isInteger(d.indexOrder) ? { order: d.indexOrder } : {}),
}));
writeIf(path.join(root, "lib/case-study-detail-cards.generated.json"), JSON.stringify(cards, null, 2) + "\n");

const START = "    // BEGIN generated: detailed case studies (scripts/generate-case-study-detail-pages.mjs)";
const END = "    // END generated: detailed case studies";
const sitemapFile = path.join(root, "app/sitemap.ts");
const sm = fs.readFileSync(sitemapFile, "utf8");
const a = sm.indexOf(START), b = sm.indexOf(END);
if (a < 0 || b < 0) { console.error(`app/sitemap.ts is missing the markers:\n${START}\n${END}`); process.exit(1); }
const entries = cases.map((d) => `    { url: \`\${base}/case-studies/${d.slug}\`, lastModified: lastMod("/case-studies/${d.slug}"), changeFrequency: "monthly", priority: 0.6 },`);
writeIf(sitemapFile, sm.slice(0, a) + [START, ...entries, END].join("\n") + sm.slice(b + END.length));

if (CHECK) {
  if (stale) process.exit(1);
  console.log(`[case-study-pages] ok (${cases.length} pages)`);
} else console.log(`[case-study-pages] wrote ${wrote} file(s), ${cases.length} pages`);
