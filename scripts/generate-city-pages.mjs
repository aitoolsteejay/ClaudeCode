// Writes app/b2b-lead-generation-<slug>/page.tsx for every file in content/city-pages/ (the files the Keystatic
// admin edits). Each page is thin on purpose: literal metadata (so the sitemap, llms-full and site-audit tooling
// that read page files see real text) and a call to <CityPage data={...} />, which renders the rest from the JSON.
// A city page also needs its entry in app/sitemap.ts and its questions in content/faqs/pages/city-<slug>.json;
// the generator warns when either is missing.
//
//   node scripts/generate-city-pages.mjs           write the pages
//   node scripts/generate-city-pages.mjs --check   exit 1 if any page is out of date
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const CHECK = process.argv.includes("--check");
const dir = path.join(root, "content/city-pages");
const j = (v) => JSON.stringify(v);

const REQUIRED = ["metaTitle", "metaDescription", "ogTitle", "ogDescription", "breadcrumbLabel", "badge", "h1", "intro", "primaryCta", "secondaryCta", "whyTitle", "servicesTitle", "servicesIntro", "diffTitle", "formTitle", "formSubtitle"];

const page = (d) => `// Generated by scripts/generate-city-pages.mjs from content/city-pages/${d.slug}.json. Edit the data, not this file.
import type { Metadata } from "next";
import CityPage from "@/components/city/CityPage";
import data from "@/content/city-pages/${d.slug}.json";

export const metadata: Metadata = {
  title: ${j(d.metaTitle)},
  description: ${j(d.metaDescription)},
  alternates: { canonical: "https://www.myntmore.com/b2b-lead-generation-${d.slug}" },
  keywords: ${j(d.keywords)},
  openGraph: {
    title: ${j(d.ogTitle)},
    description: ${j(d.ogDescription)},
    url: "https://www.myntmore.com/b2b-lead-generation-${d.slug}",
    images: [{ url: "/og-image.png", width: 1200, height: 630, alt: "Myntmore" }],
  },
};

export default function Page() {
  return <CityPage data={data} />;
}
`;

const problems = [];
const sitemap = fs.readFileSync(path.join(root, "app/sitemap.ts"), "utf8");
let wrote = 0, current = 0;
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort()) {
  const slug = f.replace(/\.json$/, "");
  const d = { ...JSON.parse(fs.readFileSync(path.join(dir, f), "utf8")), slug };
  for (const k of REQUIRED) if (!d[k]) problems.push(`${f}: "${k}" is empty`);
  for (const [k, n] of [["why", 3], ["services", 7], ["differentiators", 4]]) if (!Array.isArray(d[k]) || d[k].length !== n) problems.push(`${f}: "${k}" must have exactly ${n} items`);
  if (d.segments.length && d.segments.length !== 3) problems.push(`${f}: "segments" must have exactly 3 items, or none`);
  if (d.metaTitle && d.metaTitle.length + " | Myntmore".length > 60) console.warn(`[city-pages] warning: ${f}: search title is ${d.metaTitle.length + 11} characters with the site suffix, over 60 (Google may cut it)`);
  if (!sitemap.includes(`/b2b-lead-generation-${slug}\``)) console.warn(`[city-pages] warning: /b2b-lead-generation-${slug} is not listed in app/sitemap.ts`);
  if (!fs.existsSync(path.join(root, "content/faqs/pages", `city-${slug}.json`))) console.warn(`[city-pages] warning: content/faqs/pages/city-${slug}.json is missing, so the page has no FAQs`);
  const file = path.join(root, "app", `b2b-lead-generation-${slug}`, "page.tsx");
  const next = page(d);
  const prev = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  if (prev === next) current++;
  else if (CHECK) problems.push(`${path.relative(root, file)} is out of date`);
  else { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, next); wrote++; }
}
if (problems.length) { console.error(problems.join("\n")); process.exit(1); }
console.log(CHECK ? `[city-pages] ok (${current} pages)` : `[city-pages] wrote ${wrote} page(s), ${current} already current`);
