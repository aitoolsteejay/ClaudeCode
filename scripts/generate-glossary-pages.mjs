// Builds the glossary from content/glossary/*.json (the files the Keystatic admin edits):
//   - app/resources/glossary/<slug>/page.tsx   one thin page per term: literal metadata (so the
//     sitemap, llms-full and site-audit tooling that read page files see real text) and a call to
//     <GlossaryTerm />, which renders the term
//   - lib/glossary-index.generated.json        the card data the A-Z index page reads
//   - the term entries in app/sitemap.ts       between two marker comments
// The four longer-form terms that have their own hand-built pages (total-conversional-market,
// signal-heavy-structuring, 3-second-rule, inbound-vs-outbound) are not in content/glossary.
//
//   node scripts/generate-glossary-pages.mjs           write everything
//   node scripts/generate-glossary-pages.mjs --check   exit 1 if anything is out of date
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const CHECK = process.argv.includes("--check");
const dir = path.join(root, "content/glossary");
const j = (v) => JSON.stringify(v);

const REQUIRED = ["title", "tag", "accent", "tagline", "excerpt", "definition", "body", "sourceLabel", "sourceHref", "schemaDescription", "metaTitleSuffix", "ogTitleSuffix", "metaDescription"];

const page = (d) => `// Generated by scripts/generate-glossary-pages.mjs from content/glossary/${d.slug}.json. Edit the data, not this file.
import type { Metadata } from "next";
import GlossaryTerm from "@/components/glossary/GlossaryTerm";
import { buildDefinedTermSchema, SITE_URL } from "@/lib/schema";

const SLUG = ${j(d.slug)};
const PAGE_URL = \`\${SITE_URL}/resources/glossary/\${SLUG}\`;
const TITLE = ${j(d.title)};
const DESCRIPTION = ${j(d.schemaDescription)};
${d.alsoKnownAs.length ? `const ALSO_KNOWN_AS = ${j(d.alsoKnownAs)};\n` : ""}const META_DESCRIPTION = ${j(d.metaDescription)};

export const metadata: Metadata = {
  title: \`\${TITLE} | ${d.metaTitleSuffix}\`,
  description: META_DESCRIPTION,
  alternates: { canonical: PAGE_URL },
  keywords: ${j(d.keywords)},
  openGraph: {
    title: \`\${TITLE} | ${d.ogTitleSuffix}\`,
    description: META_DESCRIPTION,
    url: PAGE_URL,
    images: [{ url: "/og-image.png", width: 1200, height: 630, alt: "Myntmore" }],
  },
};
${
  d.faqs.length
    ? `
const FAQS = [
${d.faqs.map((f) => `  { question: ${j(f.question)}, answer: ${j(f.answer)} },`).join("\n")}
];
`
    : ""
}
const TERM_SCHEMA = buildDefinedTermSchema({
  name: TITLE,
  description: DESCRIPTION,
  url: PAGE_URL,
  inDefinedTermSet: \`\${SITE_URL}/resources/glossary\`,${d.alsoKnownAs.length ? "\n  alternateName: ALSO_KNOWN_AS," : ""}
});

export default function GlossaryTermPage() {
  return (
    <GlossaryTerm
      slug={SLUG}
      tag={${j(d.tag)}}
      accent={${j(d.accent)}}
      title={TITLE}${d.alsoKnownAs.length ? "\n      alsoKnownAs={ALSO_KNOWN_AS}" : ""}
      tagline={${j(d.tagline)}}
      definition={${j(d.definition)}}
      body={${j(d.body)}}
      sourceLabel={${j(d.sourceLabel)}}
      sourceHref={${j(d.sourceHref)}}${d.furtherLabel && d.furtherHref ? `\n      furtherLabel={${j(d.furtherLabel)}}\n      furtherHref={${j(d.furtherHref)}}` : ""}
      articleSchema={TERM_SCHEMA}${d.faqs.length ? "\n      faqs={FAQS}" : ""}
    />
  );
}
`;

const problems = [];
const terms = [];
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort()) {
  const slug = f.replace(/\.json$/, "");
  const d = { ...JSON.parse(fs.readFileSync(path.join(dir, f), "utf8")), slug };
  for (const k of REQUIRED) if (!d[k]) problems.push(`${f}: "${k}" is empty`);
  d.alsoKnownAs ??= [];
  d.faqs ??= [];
  d.keywords ??= [];
  if (d.metaDescription && d.metaDescription.length > 160) problems.push(`${f}: search description is ${d.metaDescription.length} characters, over 160`);
  terms.push(d);
}
if (problems.length) {
  console.error(problems.join("\n"));
  process.exit(1);
}

let stale = 0, wrote = 0;
const writeIf = (file, next) => {
  const prev = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  if (prev === next) return;
  stale++;
  if (!CHECK) { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, next); wrote++; }
  else console.error(`${path.relative(root, file)} is out of date`);
};

for (const d of terms) writeIf(path.join(root, "app/resources/glossary", d.slug, "page.tsx"), page(d));

// The A-Z index cards.
const cards = terms.map((d) => ({
  href: `/resources/glossary/${d.slug}`,
  tag: d.tag,
  title: d.indexTitle || d.title,
  excerpt: d.excerpt,
  accent: d.accent,
  ...(d.indexAliases && d.indexAliases.length ? { aliases: d.indexAliases } : {}),
}));
writeIf(path.join(root, "lib/glossary-index.generated.json"), JSON.stringify(cards, null, 2) + "\n");

// Sitemap entries between marker comments.
const START = "    // BEGIN generated: glossary terms (scripts/generate-glossary-pages.mjs)";
const END = "    // END generated: glossary terms";
const sitemapFile = path.join(root, "app/sitemap.ts");
const sm = fs.readFileSync(sitemapFile, "utf8");
const a = sm.indexOf(START), b = sm.indexOf(END);
if (a < 0 || b < 0) { console.error(`app/sitemap.ts is missing the markers:\n${START}\n${END}`); process.exit(1); }
const entries = terms.map((d) => `    { url: \`\${base}/resources/glossary/${d.slug}\`, lastModified: lastMod("/resources/glossary/${d.slug}"), changeFrequency: "monthly", priority: 0.6 },`);
writeIf(sitemapFile, sm.slice(0, a) + [START, ...entries, END].join("\n") + sm.slice(b + END.length));

if (CHECK) {
  if (stale) process.exit(1);
  console.log(`[glossary] ok (${terms.length} terms)`);
} else console.log(`[glossary] wrote ${wrote} file(s), ${terms.length} terms`);
