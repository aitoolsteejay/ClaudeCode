// Writes app/lp/<slug>/page.tsx for every file in content/landing-pages/ (the files the
// Keystatic admin edits). The pages are thin on purpose, like the case study pages: literal
// metadata, so the sitemap, llms-full and site-audit tooling that read page files see a real
// title, and a call to <LandingPage data={...} />, which renders everything else from the JSON.
//
//   node scripts/generate-landing-pages.mjs           write the pages
//   node scripts/generate-landing-pages.mjs --check   exit 1 if any page is out of date
//
// Each page also needs its entry in app/sitemap.ts; that file is not edited here. A landing
// page whose slug is missing from the sitemap is reported as a warning.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const CHECK = process.argv.includes("--check");
const dir = path.join(root, "content/landing-pages");

const COUNTS = { stats: 4, pain: 3, flowTop: 3, flowParallel: 3, flowBottom: 3, process: 4, track: 4, floatingIcons: 4 };
const j = JSON.stringify;

const page = (d) => `// Generated by scripts/generate-landing-pages.mjs from content/landing-pages/${d.slug}.json. Edit the data, not this file.
import type { Metadata } from "next";
import LandingPage from "@/components/lp/LandingPage";
import data from "@/content/landing-pages/${d.slug}.json";

export const metadata: Metadata = {
  title: ${j(d.metaTitle)},
  description: ${j(d.metaDescription)},
  keywords: ${j(d.keywords, null, 4).replace(/\n}/g, "\n  }").replace(/\]$/, "  ]")},
  alternates: { canonical: "https://www.myntmore.com/lp/${d.slug}" },
  openGraph: {
    title: ${j(d.ogTitle)},
    description: ${j(d.ogDescription)},
    url: "https://www.myntmore.com/lp/${d.slug}",
    images: [{ url: "/og-image.png", width: 1200, height: 630, alt: "Myntmore" }],
  },
};

export default function Page() {
  return <LandingPage data={data} />;
}
`;

const problems = [];
const sitemap = fs.readFileSync(path.join(root, "app/sitemap.ts"), "utf8");
let wrote = 0, current = 0;
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".json")).sort()) {
  const slug = f.replace(/\.json$/, "");
  const d = { ...JSON.parse(fs.readFileSync(path.join(dir, f), "utf8")), slug };
  for (const [k, n] of Object.entries(COUNTS)) if (!Array.isArray(d[k]) || d[k].length !== n) problems.push(`${f}: "${k}" must have exactly ${n} items`);
  if (d.metaTitle && d.metaTitle.length + " | Myntmore".length > 60) problems.push(`${f}: search title is ${d.metaTitle.length + 11} characters with the site suffix, over 60`);
  if (d.metaDescription && d.metaDescription.length > 155) problems.push(`${f}: search description is ${d.metaDescription.length} characters, over 155`);
  if (!sitemap.includes(`/lp/${slug}\``)) console.warn(`[landing-pages] warning: /lp/${slug} is not listed in app/sitemap.ts`);
  const file = path.join(root, "app/lp", slug, "page.tsx");
  const next = page(d);
  const prev = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : "";
  if (prev === next) current++;
  else if (CHECK) problems.push(`${path.relative(root, file)} is out of date`);
  else { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, next); wrote++; }
}
if (problems.length) { console.error(problems.join("\n")); process.exit(1); }
console.log(CHECK ? `[landing-pages] ok (${current} pages)` : `[landing-pages] wrote ${wrote} page(s), ${current} already current`);
